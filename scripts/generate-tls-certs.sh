#!/usr/bin/env bash
# scripts/generate-tls-certs.sh
# Generates self-signed TLS keypairs for each server component.
# Output: certs/  directory at the project root.

set -euo pipefail

RED='\033[0;31m'; GREEN='\033[0;32m'; NC='\033[0m'
info() { echo -e "${GREEN}[INFO]${NC}  $*"; }
abort() { echo "[ERR] $*" >&2; exit 1; }

[[ "$EUID" -ne 0 ]] || abort "Run this script as the project owner, not root, so proxy key access stays limited to your user group."

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd -- "$SCRIPT_DIR/.." && pwd)"
CERT_DIR="$PROJECT_ROOT/certs"
OVERRIDE_PATH="$PROJECT_ROOT/docker-compose.override.yml"
CERT_GROUP_ID="$(id -g)"
OVERRIDE_TMP="$(mktemp "$PROJECT_ROOT/.docker-compose.override.yml.XXXXXX")"
trap 'rm -f "$OVERRIDE_TMP"' EXIT

cat > "$OVERRIDE_TMP" <<EOF
# Generated by scripts/generate-tls-certs.sh. Do not edit this file.
services:
    proxy-guard:
        group_add:
            - "$CERT_GROUP_ID"
        environment:
            TLS_CERT_FILE: /certs/cert.pem
            TLS_KEY_FILE: /certs/key.pem
        volumes:
            - ./certs/proxy-guard:/certs:ro

    proxy-middle:
        group_add:
            - "$CERT_GROUP_ID"
        environment:
            TLS_CERT_FILE: /certs/cert.pem
            TLS_KEY_FILE: /certs/key.pem
        volumes:
            - ./certs/proxy-middle:/certs:ro

    proxy-exit:
        group_add:
            - "$CERT_GROUP_ID"
        environment:
            TLS_CERT_FILE: /certs/cert.pem
            TLS_KEY_FILE: /certs/key.pem
        volumes:
            - ./certs/proxy-exit:/certs:ro
EOF

if [[ -e "$OVERRIDE_PATH" ]] && ! cmp -s "$OVERRIDE_TMP" "$OVERRIDE_PATH"; then
        abort "$OVERRIDE_PATH already exists and is not the generated TLS override; preserving it. Move it aside or merge the TLS settings manually."
fi

mkdir -p "$CERT_DIR"

# Key size — 4096 for production, 2048 acceptable for internal dev
KEY_BITS=4096

# Days until expiry
DAYS=365

generate_cert() {
    local name="$1"
    local cn="$2"
    local out_dir="$CERT_DIR/$name"
    mkdir -p "$out_dir"

    info "Generating keypair for: $cn"

    openssl req -x509 -newkey rsa:${KEY_BITS} \
        -keyout "$out_dir/key.pem" \
        -out    "$out_dir/cert.pem" \
        -days   "${DAYS}" \
        -nodes \
        -subj   "/CN=${cn}/O=AnonChat/C=XX" \
        -addext "subjectAltName=DNS:${cn},DNS:localhost,IP:127.0.0.1"

    chmod 640 "$out_dir/key.pem"
    chmod 644 "$out_dir/cert.pem"

    info "  cert: $out_dir/cert.pem"
    info "  key:  $out_dir/key.pem"
}

generate_cert "proxy-guard"  "proxy-guard"
generate_cert "proxy-middle" "proxy-middle"
generate_cert "proxy-exit"   "proxy-exit"

chmod 644 "$OVERRIDE_TMP"
mv "$OVERRIDE_TMP" "$OVERRIDE_PATH"
info "All certificates generated in: $CERT_DIR"
echo ""
info "Generated Docker Compose TLS configuration: $OVERRIDE_PATH"
echo "Run 'docker compose config' to review the merged configuration."